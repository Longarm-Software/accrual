// Pre-bundles Actual's engine (@actual-app/core, a.k.a. loot-core) into one
// CommonJS file that Metro/Hermes can load, swapping loot-core's platform
// modules for the React Native shims in ./shims.
//
// platform: 'neutral' is deliberate: any Node builtin that is still reachable
// fails the build instead of failing on the phone.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import * as esbuild from 'esbuild';
import peggy from 'peggy';

const here = path.dirname(fileURLToPath(import.meta.url));
const coreRoot = path.join(here, '..', 'node_modules', '@actual-app', 'core');
const shim = name => path.join(here, 'shims', name);

// 1. Embed the default budget DB and the SQL migrations.
const migrationsDir = path.join(coreRoot, 'migrations');
const migrations = {};
for (const name of fs.readdirSync(migrationsDir).sort()) {
  if (name.endsWith('.sql')) migrations[name] = fs.readFileSync(path.join(migrationsDir, name), 'utf8');
  // JS migrations are compiled into loot-core; only their names are needed.
  if (name.endsWith('.js')) migrations[name] = '';
}
fs.mkdirSync(path.join(here, 'generated'), { recursive: true });
fs.writeFileSync(
  path.join(here, 'generated', 'embedded-assets.ts'),
  `// GENERATED by engine/build.mjs from @actual-app/core. Do not edit.\n` +
    `export const defaultDbBase64 = ${JSON.stringify(
      fs.readFileSync(path.join(coreRoot, 'default-db.sqlite')).toString('base64'),
    )};\n` +
    `export const migrations: Record<string, string> = ${JSON.stringify(migrations, null, 1)};\n`,
);

// 2. Platform seams: loot-core import specifier -> our implementation.
const overrides = {
  '#platform/server/sqlite': shim('sqlite.ts'),
  '#platform/server/fs': shim('fs.ts'),
  '#platform/server/fs/path-join': shim('path-join.ts'),
  '#platform/server/asyncStorage': shim('async-storage.ts'),
  '#platform/server/fetch': shim('fetch.ts'),
  '#platform/server/memory': shim('memory.ts'),
  '#server/encryption/encryption-internals': shim('encryption-internals.ts'),
  'node:crypto': shim('node-crypto.ts'),
  // Third-party packages that reach for Node builtins:
  timers: shim('timers.ts'), // xml2js
  events: path.join(here, '..', 'node_modules', 'events', 'events.js'), // xml2js
  handlebars: path.join(here, '..', 'node_modules', 'handlebars', 'dist', 'cjs', 'handlebars.js'), // main entry needs fs
};

const platformPlugin = {
  name: 'accrual-platform',
  setup(build) {
    build.onResolve({ filter: /^(#|node:|timers$|events$|handlebars$)/ }, args =>
      overrides[args.path] ? { path: overrides[args.path] } : undefined,
    );
    build.onLoad({ filter: /\.pegjs$/ }, async args => ({
      contents: peggy.generate(await fs.promises.readFile(args.path, 'utf8'), {
        output: 'source',
        format: 'es',
      }),
      loader: 'js',
    }));
  },
};

const result = await esbuild.build({
  entryPoints: [path.join(here, 'entry.ts')],
  outfile: path.join(here, 'dist', 'loot-core.rn.js'),
  bundle: true,
  format: 'cjs',
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  conditions: ['api'],
  external: ['expo-sqlite', 'expo-file-system', 'expo-crypto', 'expo/fetch'],
  define: {
    'process.env.NODE_ENV': '"production"',
    'process.env.IS_DEV': 'false',
  },
  plugins: [platformPlugin],
  metafile: true,
  legalComments: 'none',
  logLevel: 'info',
});
fs.writeFileSync(path.join(here, 'dist', 'meta.json'), JSON.stringify(result.metafile));
